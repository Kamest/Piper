    def test_legacy_agents_link_original_files_and_replace_old_filtered_copy(self):
        import tempfile
        from pathlib import Path
        with tempfile.TemporaryDirectory() as directory:
            src, dst = Path(directory) / "original", Path(directory) / "legacy/agents"
            allow = src / "custom/allow.txt"
            allow.parent.mkdir(parents=True)
            content = "# comment\napi.example.com\nGITLAB.EXAMPLE.COM:443\n"
            allow.write_text(content)
            dst.mkdir(parents=True)
            (dst / "stale.txt").write_text("old filtered snapshot")
            holehome.link_agents(str(src), str(dst))
            self.assertTrue(dst.is_symlink())
            self.assertTrue((dst / "custom/allow.txt").samefile(allow))
            self.assertEqual(allow.read_text(), content)
            self.assertFalse((dst / "stale.txt").exists())
            inode = dst.lstat().st_ino
            self.assertEqual(holehome.link_agents(str(src), str(dst)), [])
            self.assertEqual(dst.lstat().st_ino, inode)
            allow.write_text(content + "new.example.com\n")
            self.assertEqual((dst / "custom/allow.txt").read_text(), allow.read_text())

    def test_agent_link_supports_missing_and_symlinked_original_registry(self):
        import tempfile
        from pathlib import Path
        with tempfile.TemporaryDirectory() as directory:
            src, dst = Path(directory) / "original", Path(directory) / "agents"
            holehome.link_agents(str(src), str(dst))
            self.assertTrue(dst.is_symlink())
            actual = Path(directory) / "installed"
            actual.mkdir()
            src.symlink_to(actual, target_is_directory=True)
            (actual / "allow.txt").write_text("gitlab.com\n")
            self.assertTrue((dst / "allow.txt").samefile(actual / "allow.txt"))

