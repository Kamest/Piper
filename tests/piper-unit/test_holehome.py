    def test_wrapper_runs_a_non_executable_script_with_real_home_and_expanded_vars(self):
        import subprocess
        import tempfile
        d = tempfile.mkdtemp()
        os.makedirs(os.path.join(d, "proj", "scripts"))
        script = os.path.join(d, "proj", "scripts", "hook.sh")
        with open(script, "w") as f:
            f.write('echo "HOME=$HOME"\n')
        os.chmod(script, 0o644)   # like the personal setup-host.sh: not executable
        os.environ["PIPER_TEST_PP"] = os.path.join(d, "proj")
        out, _ = holehome.generate({"hooks": {"setupHost": [{"script": "$PIPER_TEST_PP/scripts/hook.sh"}]}},
                                   "/real/home", None, {"hook_wrap_dir": os.path.join(d, "w")})
        wrapper = out["hooks"]["setupHost"][0]["script"]
        r = subprocess.run(["bash", wrapper], capture_output=True, text=True, env=dict(os.environ, HOME="/hole-home"))
        self.assertEqual((r.returncode, r.stdout.strip()), (0, "HOME=/real/home"), r.stderr)
        self.assertNotIn("libraries", out["profiles"]["advisor"])

