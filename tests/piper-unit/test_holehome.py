    def test_protected_overlaps_are_dropped(self):
        """guard.preflight blocks any mount overlapping a protected dir: the generator must not
        emit one (a personal token in ~/.hole, a data library holding a tool's state dir)."""
        doc = {"files": {"include": {"~/.hole/stack-token": "~/.stack-token",
                                     "~/.hole/claude-config/sandbox.json": "~/.claude.json",
                                     "~/.m2/repository": "~/.m2/repository"}},
               "libraries": {"~/www/data": {"path": "~/www/data", "readwrite": True},
                             "~/www/projects/lib": "~/www/projects/lib"},
               "profiles": {"x": {"files": {"include": {"~/.hole/y": "~/y"}}}}}
        rules = {"protected": [HOME + "/.hole", HOME + "/www/data/state"]}
        out, changes = holehome.generate(doc, HOME, "/p", rules)
        self.assertEqual(out["files"]["include"], {HOME + "/.m2/repository": "~/.m2/repository"})
        self.assertEqual(set(out["profiles"]["project"]["libraries"]), {HOME + "/www/projects/lib"})
        self.assertEqual(out["profiles"]["x"]["files"]["include"], {})
        joined = "\n".join(changes)
        self.assertIn("stack-token -> ~/.stack-token removed (overlaps protected", joined)
        self.assertIn("libraries ~/www/data removed (overlaps protected", joined)

    def test_library_holding_a_protected_dir_is_split(self):
        """W1: ~/www/data holds a tool's state dir - its data subtrees stay mounted (the stacks bind
        them, keep their readwrite), only state/ and loose files are cut out, nested ones too."""
        import tempfile
        home = tempfile.mkdtemp()
        pd = os.path.join(home, "www", "data")
        for d in ("state/jobs", "maven-m2", "shop/db", "deep/state2", "deep/keep"):
            os.makedirs(os.path.join(pd, d))
        open(os.path.join(pd, "projects.index"), "w").close()
        doc = {"libraries": {"~/www/data": {"path": "~/www/data", "readwrite": True}}}
        rules = {"protected": [pd + "/state", pd + "/deep/state2"], "keep_rw_libraries": True}
        out, changes = holehome.generate(doc, home, "/p", rules)
        libs = out["profiles"]["project"]["libraries"]
        self.assertEqual(libs, {pd + "/maven-m2": {"path": "~/www/data/maven-m2", "readwrite": True},
                                pd + "/shop": {"path": "~/www/data/shop", "readwrite": True},
                                pd + "/deep/keep": {"path": "~/www/data/deep/keep", "readwrite": True}})
        joined = "\n".join(changes)
        self.assertIn("libraries %s/state removed (overlaps protected" % pd, joined)
        self.assertIn("libraries ~/www/data mounted as %s/maven-m2" % pd, joined)
        out, changes = holehome.generate(doc, home, "/p", dict(rules, keep_rw_libraries=False))
        self.assertNotIn("readwrite", out["profiles"]["project"]["libraries"][pd + "/shop"])
        out, _ = holehome.generate(doc, home, "/p", dict(rules, keep_rw_libraries=False,
                                                          rw_libraries=["~/www/data"]))
        self.assertTrue(out["profiles"]["project"]["libraries"][pd + "/shop"]["readwrite"])
        # a library inside a protected dir stays removed whole
        out, _ = holehome.generate({"libraries": {pd + "/state/jobs": pd + "/state/jobs"}}, home, "/p", rules)
        self.assertNotIn("libraries", out["profiles"]["project"])

